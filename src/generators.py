def filter_by_currency(transactions, currency_code):
    """ Фильтрует транзакции по валюте. Возвращает генератор.

    Аргументы:
        transactions: список транзакций (словарей)
        currency_code: код валюты для фильтрации (например, "USD")

    Возвращает:
        Генератор транзакций с указанной валютой"""

    # Перебираем все транзакции
    for transaction in transactions:
        # Получаем код валюты текущей транзакции
        currency = transaction["operationAmount"]["currency"]["code"]

        # Если валюта совпадает с искомой
        if currency == currency_code:
            # Возвращаем транзакцию (yield делает функцию генератором)
            yield transaction


def transaction_descriptions(transactions):
    """Возвращает генератор описаний транзакций.

    Аргументы:
        transactions: список транзакций (словарей)

    Возвращает:
        Генератор, который по очереди возвращает описания операций"""

    # Перебираем все транзакции
    for transaction in transactions:
        # Возвращаем описание текущей транзакции
        # yield приостанавливает функцию и возвращает значение
        # При следующем вызове next() функция продолжит со следующей транзакции
        yield transaction['description']


def card_number_generator(start, end):
    """ Генератор номеров банковских карт.

    Аргументы:
        start (int): начальный номер (минимально 1)
        end (int): конечный номер (максимально 9999 9999 9999 9999)

   Возвращает:
        str: номера карт в заданном диапазоне"""
    # Перебираем все числа от start до end
    # +1 потому что range не включает последнее число
    for number in range(start, end + 1):
        # Превращаем число в строку
        number_str = str(number)

        # Создаём строку из 16 нулей
        # Это будет шаблон, который мы заполним
        sixteen_zeros = "0000000000000000"

        # Вычисляем сколько цифр в нашем числе
        # Например: "42" имеет длину 2, "1" имеет длину 1
        number_length = len(number_str)

        # Отрезаем от строки нулей столько символов справа,
        # сколько цифр в нашем числе
        # Например: для "42" (2 цифры) отрезаем 2 нуля
        # "0000000000000000" → "00000000000000"
        zeros_without_last = sixteen_zeros[:-number_length]

        # К оставшимся нулям добавляем наше число
        # "00000000000000" + "42" = "0000000000000042"
        card_without_spaces = zeros_without_last + number_str

        # Разбиваем 16 цифр на 4 группы по 4 цифры
        # Берём срезы строки:
        # - цифры с 0 по 4 (первые 4 цифры)
        # - цифры с 4 по 8 (вторые 4 цифры)
        # - цифры с 8 по 12 (третьи 4 цифры)
        # - цифры с 12 по 16 (четвёртые 4 цифры)
        part1 = card_without_spaces[0:4]  # первые 4 цифры
        part2 = card_without_spaces[4:8]  # вторые 4 цифры
        part3 = card_without_spaces[8:12]  # третьи 4 цифры
        part4 = card_without_spaces[12:16]  # четвёртые 4 цифры

        # Собираем группы с пробелами между ними
        # "0000" + " " + "0000" + " " + "0000" + " " + "0042"
        formatted_card = part1 + " " + part2 + " " + part3 + " " + part4

        # Возвращаем готовый номер карты
        # yield делает функцию генератором - она будет возвращать
        # по одному номеру за раз, не создавая весь список сразу
        yield formatted_card